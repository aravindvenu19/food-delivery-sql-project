#20. Find the number of orders placed in each month.

select substr(order_time, 1, 7) as order_month,count(order_id) as total_orders
from orders_medium group by order_month order by order_month;

#21. Find restaurants whose rating is between 4 and 5 and cuisine is either Indian or Chinese.

